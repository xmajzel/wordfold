#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import process from 'node:process';

const ROOT = resolve(import.meta.dirname, '..');
const CATALOG_PATH = resolve(ROOT, 'assets/catalog/cefr-catalog.json');
const OUTPUT_PATH = resolve(
  ROOT,
  'supabase/migrations/20260721180500_seed_pronunciation_catalog_inputs.sql',
);
const BATCH_SIZE = 500;

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function validateEntries(payload) {
  const entries = Array.isArray(payload) ? payload : payload?.entries;
  if (!Array.isArray(entries) || entries.length !== 8300) {
    throw new Error('CEFR catalog must contain exactly 8,300 entries.');
  }
  const ids = new Set();
  for (const entry of entries) {
    if (typeof entry?.catalogSenseId !== 'string' || !entry.catalogSenseId.trim()) {
      throw new Error('Every CEFR entry requires a catalogSenseId.');
    }
    if (ids.has(entry.catalogSenseId)) throw new Error(`Duplicate catalogSenseId ${entry.catalogSenseId}.`);
    ids.add(entry.catalogSenseId);
    if (typeof entry.term !== 'string' || entry.term !== entry.term.trim()
      || entry.term.length === 0 || entry.term.length > 200 || entry.term.includes('\0')) {
      throw new Error(`${entry.catalogSenseId} has invalid pronunciation text.`);
    }
    if (!['cefr-j', 'octanove'].includes(entry.source)) {
      throw new Error(`${entry.catalogSenseId} has unsupported source ${String(entry.source)}.`);
    }
    if (typeof entry.sourceVersion !== 'string' || !entry.sourceVersion.trim()) {
      throw new Error(`${entry.catalogSenseId} requires sourceVersion.`);
    }
  }
  return [...entries].sort((left, right) => left.catalogSenseId.localeCompare(right.catalogSenseId));
}

function buildSql(entries, catalogSha256) {
  const lines = [
    '-- Generated by scripts/build-pronunciation-catalog-sql.mjs. Do not edit by hand.',
    `-- Source: assets/catalog/cefr-catalog.json (${entries.length} entries, SHA-256 ${catalogSha256})`,
    '',
  ];
  for (let offset = 0; offset < entries.length; offset += BATCH_SIZE) {
    const batch = entries.slice(offset, offset + BATCH_SIZE);
    lines.push(
      'insert into public.pronunciation_catalog_inputs (',
      '  catalog_sense_id, text, source, source_version, catalog_sha256',
      ') values',
      batch.map((entry) => `  (${[
        sqlString(entry.catalogSenseId),
        sqlString(entry.term),
        sqlString(entry.source),
        sqlString(entry.sourceVersion),
        sqlString(catalogSha256),
      ].join(', ')})`).join(',\n') + ';',
      '',
    );
  }
  return lines.join('\n');
}

async function main() {
  const check = process.argv.slice(2).includes('--check');
  const source = await readFile(CATALOG_PATH);
  const entries = validateEntries(JSON.parse(source.toString('utf8')));
  const catalogSha256 = createHash('sha256').update(source).digest('hex');
  const sql = buildSql(entries, catalogSha256);
  if (check) {
    const existing = await readFile(OUTPUT_PATH, 'utf8');
    if (existing !== sql) throw new Error('Pronunciation catalog SQL is stale. Rebuild it.');
    console.log(`Valid pronunciation catalog SQL: ${entries.length} entries, ${catalogSha256}.`);
    return;
  }
  await writeFile(OUTPUT_PATH, sql, 'utf8');
  console.log(`Wrote ${entries.length} pronunciation catalog inputs to ${OUTPUT_PATH}.`);
}

main().catch((error) => {
  console.error(`Error: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
