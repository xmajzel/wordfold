const { withProjectBuildGradle } = require('expo/config-plugins');

const marker = '// @generated by with-android-workmanager-version';

module.exports = function withAndroidWorkManagerVersion(config) {
  return withProjectBuildGradle(config, (result) => {
    if (result.modResults.language !== 'groovy' || result.modResults.contents.includes(marker)) {
      return result;
    }

    result.modResults.contents += `

${marker}
allprojects {
  configurations.all {
    resolutionStrategy {
      force 'androidx.work:work-runtime:2.8.1'
      force 'androidx.work:work-runtime-ktx:2.8.1'
    }
  }
}
`;

    return result;
  });
};
